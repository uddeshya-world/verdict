func TestJarWarNested(t *testing.T) {
	war := buildZip(t,
		zentry{name: "WEB-INF/web.xml", body: []byte("<web-app/>")},
		zentry{name: "WEB-INF/lib/log4j-core-2.17.1.jar", body: log4jCore(t, "2.17.1", true), store: true},
	)
	got, err := Jar([]JarInput{{Name: "app.war", Data: war}}, jarOpts())
	if err != nil {
		t.Fatal(err)
	}
	a := got.Snapshot.Assets[0]
	if !hasPURL(a, "pkg:maven/org.apache.logging.log4j/log4j-core@2.17.1") || len(a.Inventory.Packages) != 1 {
		t.Fatalf("%+v", a.Inventory.Packages)
	}
	if f := fact(a, JndiLookupFactKey); f == nil || f.Value != "present" || !strings.Contains(f.Source, "app.war!/WEB-INF/lib/log4j-core-2.17.1.jar") {
		t.Fatalf("%+v", f)
	}
	// The WAR itself has no coordinates, so it is skipped and --complete is refused.
	if len(got.Skipped) != 1 || !strings.HasPrefix(got.Skipped[0], "app.war:") {
		t.Fatalf("%v", got.Skipped)
	}
	opt := jarOpts()
	opt.Complete = true
	if _, err := Jar([]JarInput{{Name: "app.war", Data: war}}, opt); err == nil || !strings.Contains(err.Error(), "cannot be complete") {
		t.Fatal(err)
	}
}

func TestJarSpringBootFatJar(t *testing.T) {
	webmvc := buildZip(t, pom("org.springframework", "spring-webmvc", "5.3.17"), class("org/springframework/web/servlet/DispatcherServlet.class"))
	beans := buildZip(t, zentry{name: "META-INF/MANIFEST.MF", body: []byte("Manifest-Version: 1.0\r\nImplementation-Title: spring-beans\r\nImplementation-Version: 5.3.17\r\n\r\n")})
	boot := buildZip(t,
		pom("com.example", "demo", "0.0.1-SNAPSHOT"),
		zentry{name: "BOOT-INF/lib/spring-webmvc-5.3.17.jar", body: webmvc, store: true},
		zentry{name: "BOOT-INF/lib/spring-beans-5.3.17.jar", body: beans, store: true},
		zentry{name: "BOOT-INF/lib/mystery-9.9.jar", body: buildZip(t, class("x/Y.class")), store: true},
	)
	opt := jarOpts()
	opt.JavaVersion = "17.0.2"
	got, err := Jar([]JarInput{{Name: "demo.jar", Data: boot}}, opt)
	if err != nil {
		t.Fatal(err)
	}
	a := got.Snapshot.Assets[0]
	for _, p := range []string{
		"pkg:maven/org.springframework/spring-webmvc@5.3.17",
		"pkg:maven/org.springframework/spring-beans@5.3.17",
		"pkg:maven/com.example/demo@0.0.1-SNAPSHOT",
	} {
		if !hasPURL(a, p) {
			t.Fatalf("missing %s in %+v", p, a.Inventory.Packages)
		}
	}
	for _, pkg := range a.Inventory.Packages {
		if strings.Contains(pkg.PURL, "mystery") {
			t.Fatal("version invented from a file name")
		}
	}
	if len(got.Skipped) != 1 || !strings.Contains(got.Skipped[0], "mystery-9.9.jar") {
		t.Fatalf("%v", got.Skipped)
	}
	if f := fact(a, JDK9FactKey); f == nil || f.Value != "true" || f.Basis != "attested" {
		t.Fatalf("%+v", f)
	}
	if fact(a, JndiLookupFactKey) != nil {
		t.Fatal("JndiLookup fact without log4j-core")
	}
}

