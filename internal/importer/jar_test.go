func TestJarOversizeEntryRejected(t *testing.T) {
	big := bytes.Repeat([]byte{0}, 4<<20) // compresses to a few KiB
	data := buildZip(t, zentry{name: "META-INF/MANIFEST.MF", body: big})
	opt := jarOpts()
	opt.Limits = DefaultJarLimits()
	opt.Limits.MaxEntryBytes = 1 << 20
	if _, err := Jar([]JarInput{{Name: "bomb.jar", Data: data}}, opt); !errors.Is(err, ErrJarLimit) {
		t.Fatalf("got %v", err)
	}
	// Total cap across several small entries.
	nested := buildZip(t,
		zentry{name: "a.jar", body: buildZip(t, zentry{name: "META-INF/MANIFEST.MF", body: big[:900<<10]})},
		zentry{name: "b.jar", body: buildZip(t, zentry{name: "META-INF/MANIFEST.MF", body: big[:900<<10]})},
	)
	opt.Limits.MaxTotalBytes = 1 << 20
	if _, err := Jar([]JarInput{{Name: "bomb2.jar", Data: nested}}, opt); !errors.Is(err, ErrJarLimit) {
		t.Fatalf("got %v", err)
	}
}

func TestJarLyingHeaderRejected(t *testing.T) {
	big := bytes.Repeat([]byte("A"), 2<<20)
	data := buildZip(t, zentry{name: "META-INF/MANIFEST.MF", body: big})
	// Rewrite the declared uncompressed size in the central directory to 10 bytes.
	cd := bytes.LastIndex(data, []byte("PK\x01\x02"))
	if cd < 0 {
		t.Fatal("no central directory")
	}
	copy(data[cd+24:cd+28], []byte{10, 0, 0, 0})
	opt := jarOpts()
	opt.Limits = DefaultJarLimits()
	opt.Limits.MaxEntryBytes = 1 << 20
	_, err := Jar([]JarInput{{Name: "liar.jar", Data: data}}, opt)
	if err == nil {
		t.Fatal("lying header accepted")
	}
}

