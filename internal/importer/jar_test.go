type zentry struct {
	name  string
	body  []byte
	store bool
}

func buildZip(t *testing.T, entries ...zentry) []byte {
	t.Helper()
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	for _, e := range entries {
		m := zip.Deflate
		if e.store {
			m = zip.Store
		}
		fw, err := w.CreateHeader(&zip.FileHeader{Name: e.name, Method: m})
		if err != nil {
			t.Fatal(err)
		}
		if _, err := fw.Write(e.body); err != nil {
			t.Fatal(err)
		}
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func pom(g, a, v string) zentry {
	return zentry{
		name: "META-INF/maven/" + g + "/" + a + "/pom.properties",
		body: []byte("#Generated by Maven\ngroupId=" + g + "\nartifactId=" + a + "\nversion=" + v + "\n"),
	}
}

func class(name string) zentry { return zentry{name: name, body: []byte{0xca, 0xfe, 0xba, 0xbe}} }

func log4jCore(t *testing.T, version string, withJndi bool) []byte {
	es := []zentry{
		{name: "META-INF/MANIFEST.MF", body: []byte("Manifest-Version: 1.0\nImplementation-Title: Apache Log4j Core\nImplementation-Version: " + version + "\n\n")},
		pom("org.apache.logging.log4j", "log4j-core", version),
		class("org/apache/logging/log4j/core/Logger.class"),
		class("org/apache/logging/log4j/core/lookup/MainMapLookup.class"),
	}
	if withJndi {
		es = append(es, class(jndiLookupClass))
	}
	return buildZip(t, es...)
}

func jarOpts() JarOptions {
	return JarOptions{
		AssetID: "lab-jar", AssetName: "lab jar", KBVersion: "demo-2026.11.08",
		Evaluation: "2026-11-08T12:00:00Z", ObservedAt: "2026-11-08T11:00:00Z",
	}
}

func fact(a snapshot.Asset, key string) *snapshot.Fact {
	for i := range a.Facts {
		if a.Facts[i].Key == key {
			return &a.Facts[i]
		}
	}
	return nil
}

func hasPURL(a snapshot.Asset, p string) bool {
	for _, pkg := range a.Inventory.Packages {
		if pkg.PURL == p {
			return true
		}
	}
	return false
}

func TestJarPlainLog4jPresent(t *testing.T) {
	data := log4jCore(t, "2.14.1", true)
	got, err := Jar([]JarInput{{Name: "/tmp/x/log4j-core-2.14.1.jar", Data: data}}, jarOpts())
	if err != nil {
		t.Fatal(err)
	}
	a := got.Snapshot.Assets[0]
	if !hasPURL(a, "pkg:maven/org.apache.logging.log4j/log4j-core@2.14.1") {
		t.Fatalf("%+v", a.Inventory.Packages)
	}
	f := fact(a, JndiLookupFactKey)
	if f == nil || f.Value != "present" || f.Basis != "observed" || f.Confidence != "high" || f.PURL != "" {
		t.Fatalf("%+v", f)
	}
	if a.Inventory.Basis != "observed" || a.Inventory.Confidence != "high" || a.Inventory.Complete {
		t.Fatalf("%+v", a.Inventory)
	}
	if strings.Contains(f.Source, "/tmp/") {
		t.Fatalf("source leaks host path: %s", f.Source)
	}
	if fact(a, JDK9FactKey) != nil {
		t.Fatal("runtime fact without --java-version")
	}
	// Deterministic: same bytes, same snapshot.
	again, err := Jar([]JarInput{{Name: "log4j-core-2.14.1.jar", Data: data}}, jarOpts())
	if err != nil {
		t.Fatal(err)
	}
	if again.Snapshot.Assets[0].Facts[0].EvidenceID != f.EvidenceID || again.Snapshot.Assets[0].Inventory.EvidenceID != a.Inventory.EvidenceID {
		t.Fatal("evidence ids are not deterministic")
	}
}

