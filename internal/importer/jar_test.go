func TestJavaMajor(t *testing.T) {
	cases := map[string]int{"1.8.0_292": 8, "17.0.2": 17, "11": 11, "9": 9, "21-ea": 21, "1.7.0": 7}
	for in, want := range cases {
		got, err := JavaMajor(in)
		if err != nil || got != want {
			t.Fatalf("%s: %d %v", in, got, err)
		}
	}
	for _, bad := range []string{"", "java", "1", "1.9", "abc.1"} {
		if _, err := JavaMajor(bad); err == nil {
			t.Fatalf("%q accepted", bad)
		}
	}
	opt := jarOpts()
	opt.JavaVersion = "1.8.0_292"
	got, err := Jar([]JarInput{{Name: "l.jar", Data: log4jCore(t, "2.14.1", true)}}, opt)
	if err != nil {
		t.Fatal(err)
	}
	if f := fact(got.Snapshot.Assets[0], JDK9FactKey); f == nil || f.Value != "false" {
		t.Fatalf("%+v", f)
	}
}
